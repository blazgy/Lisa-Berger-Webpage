// Builds a small self-hosted icons.js with only the Lucide icons the site uses, instead of
// loading the whole library (about 500 KB) from a third-party CDN. The version is pinned in
// package.json, so the icons only change when the dependency is updated on purpose.
import * as lucide from "lucide";

/**
 * Every icon name the pages may ask for. Static names in HTML/JS are checked against this list
 * at build time; names chosen at runtime (therapy-form icons, status icons) must be added here.
 */
export const ICON_NAMES = [
  // Home page and booking dialog
  "arrow-right", "arrow-left", "calendar", "calendar-check", "chevron-left", "chevron-right",
  "mail", "phone", "map-pin", "x", "check",
  // Therapy-form icons selectable in the dashboard (SERVICE_ICONS in admin.js)
  "user", "users", "puzzle", "baby", "heart", "heart-handshake", "smile", "leaf", "message-circle", "sparkles",
  // Dashboard
  "clock", "log-out", "plus", "plus-circle", "refresh-cw", "search", "settings", "trash-2",
  "triangle-alert", "info", "circle-check",
];

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

/** Returns the source of icons.js, a drop-in for `window.lucide.createIcons()`. */
export function buildIconsScript() {
  const data = {};
  for (const name of ICON_NAMES) {
    const node = lucide[pascal(name)];
    if (!Array.isArray(node)) throw new Error(`Unknown Lucide icon: ${name}`);
    data[name] = node;
  }
  return `/* Lucide icons (ISC licence, lucide.dev), subset generated by scripts/icons.mjs */
(function () {
  var ICONS = ${JSON.stringify(data)};
  var NS = "http://www.w3.org/2000/svg";
  var BASE = { xmlns: NS, width: "24", height: "24", viewBox: "0 0 24 24", fill: "none", stroke: "currentColor",
    "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round", "aria-hidden": "true" };
  function createIcons() {
    var els = document.querySelectorAll("i[data-lucide]");
    for (var i = 0; i < els.length; i++) {
      var el = els[i], name = el.getAttribute("data-lucide"), node = ICONS[name];
      if (!node) continue;
      var svg = document.createElementNS(NS, "svg"), k;
      for (k in BASE) svg.setAttribute(k, BASE[k]);
      for (var a = 0; a < el.attributes.length; a++) {
        var attr = el.attributes[a];
        if (attr.name !== "data-lucide" && attr.name !== "class") svg.setAttribute(attr.name, attr.value);
      }
      svg.setAttribute("class", ("lucide lucide-" + name + " " + (el.getAttribute("class") || "")).trim());
      for (var c = 0; c < node.length; c++) {
        var child = document.createElementNS(NS, node[c][0]);
        for (k in node[c][1]) child.setAttribute(k, node[c][1][k]);
        svg.appendChild(child);
      }
      el.replaceWith(svg);
    }
  }
  window.lucide = { createIcons: createIcons };
  createIcons();
})();
`;
}

/** Fails the build when a page uses an icon that is missing from ICON_NAMES. */
export function checkIconNames(sources) {
  const missing = new Set();
  for (const text of sources) {
    for (const m of text.matchAll(/data-lucide="([a-z0-9-]+)"|icon\("([a-z0-9-]+)"/g)) {
      const name = m[1] || m[2];
      if (!ICON_NAMES.includes(name)) missing.add(name);
    }
  }
  if (missing.size) throw new Error(`Add these icons to ICON_NAMES in scripts/icons.mjs: ${[...missing].join(", ")}`);
}
